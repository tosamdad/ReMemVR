-- 기본값은 코드(Settings::DEFAULTS)에서 켬으로 바꿨고, 예전에 저장된 꺼짐 값은 지워 새 기본값을 따르게 한다.
-- 관리자 운영 설정에서 다시 끄면 예전처럼 관리자 검토를 거친다.
-- 이 파일은 서버에 적용된 뒤에는 수정하지 않는다. 이후 변경은 0006_ 부터 새 파일로 작성한다.

DELETE FROM settings WHERE k = 'voice.auto_clone_on_submit';

-- 자주 묻는 질문의 목소리 생성 안내를 지금 흐름(바로 생성, 동화는 골라서 요청)에 맞춘다.
-- 관리자가 이미 내용을 고쳤으면 그대로 둔다(처음 넣은 문장일 때만 바꾼다).
UPDATE faqs
   SET answer = '녹음을 모두 1분 이상 마치고 완료를 누르면 AI가 바로 목소리를 만들어요. 보통 1분 안에 준비되고, 진행 상황은 목소리 연구실에서 바로 확인할 수 있어요.
목소리가 준비되면 동화 책장에서 듣고 싶은 동화를 고르고 이 목소리로 만들어 달라고 요청해 주세요. 완성된 동화는 내 동화에서 듣고 플레이리스트에 담아 반복해서 들을 수 있어요.'
 WHERE question = '목소리가 만들어지기까지 얼마나 걸리나요?'
   AND answer LIKE '녹음을 제출하면 운영팀이 녹음 상태를 확인한 뒤%';
